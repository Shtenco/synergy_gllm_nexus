def sha256_bytes(data:bytes)->str:return hashlib.sha256(data).hexdigest()
def normalized_surface(text:str)->str:return " ".join(re.sub(r"[^\w]+"," ",text.casefold(),flags=re.UNICODE).split())
def template_skeleton(text:str,subject:str,obj:str|None)->str:
    out=text.replace(subject,"<S>")
    if obj: out=out.replace(obj,"<O>")
    return normalized_surface(out)
